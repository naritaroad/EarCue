#!/usr/bin/env python3
"""Generate app/src/main/res/values*/strings.xml and xml/locales_config.xml from the tables in this folder.

Run from anywhere: python tools/i18n/gen_strings.py
Fails if a locale misses a key, has an extra key, or changes the placeholders of a string.
"""
import importlib.util
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
RES = HERE.parents[1] / "app" / "src" / "main" / "res"

# module file -> (Android resource qualifier, BCP-47 tag)
LOCALES = {
    "en": ("values", "en"),
    "zh_TW": ("values-zh-rTW", "zh-TW"),
    "zh_CN": ("values-zh-rCN", "zh-CN"),
    "es": ("values-es", "es"),
    "pt_BR": ("values-pt-rBR", "pt-BR"),
    "ja": ("values-ja", "ja"),
    "ko": ("values-ko", "ko"),
    "fr": ("values-fr", "fr"),
    "de": ("values-de", "de"),
    "ru": ("values-ru", "ru"),
}

PLACEHOLDER = re.compile(r"%\d+\$[-#+ 0,(]*\d*(?:\.\d+)?[a-zA-Z]")


def load(name):
    spec = importlib.util.spec_from_file_location(name, HERE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def escape(text):
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text.startswith(("@", "?")):
        text = "\\" + text
    return text


def write(path, entries, untranslatable=None):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/i18n/gen_strings.py. Edit the .py tables, not this file. -->", "<resources>"]
    for key, value in (untranslatable or {}).items():
        lines.append(f'    <string name="{key}" translatable="false">{escape(value)}</string>')
    for key in sorted(entries):
        lines.append(f'    <string name="{key}">{escape(entries[key])}</string>')
    lines.append("</resources>")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    base = load("en")
    errors = []
    for name, (folder, _) in LOCALES.items():
        table = base.S if name == "en" else load(name).S
        missing = base.S.keys() - table.keys()
        extra = table.keys() - base.S.keys()
        if missing:
            errors.append(f"{name}: missing {sorted(missing)}")
        if extra:
            errors.append(f"{name}: unknown {sorted(extra)}")
        for key in base.S.keys() & table.keys():
            if sorted(PLACEHOLDER.findall(base.S[key])) != sorted(PLACEHOLDER.findall(table[key])):
                errors.append(f"{name}.{key}: placeholders differ")
        if not errors:
            write(RES / folder / "strings.xml", table, base.FIXED if name == "en" else None)
    if errors:
        print("\n".join(errors))
        return 1
    locales = "\n".join(f'    <locale android:name="{tag}" />' for _, tag in LOCALES.values())
    (RES / "xml").mkdir(exist_ok=True)
    (RES / "xml" / "locales_config.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f"{locales}\n</locale-config>\n",
        encoding="utf-8",
    )
    print(f"wrote {len(LOCALES)} locales, {len(base.S)} strings each")
    return 0


if __name__ == "__main__":
    sys.exit(main())
